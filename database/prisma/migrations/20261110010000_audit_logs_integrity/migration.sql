CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE TYPE "AuditOutcome" AS ENUM ('SUCCESS', 'FAILURE', 'DENIED');

ALTER TABLE "audit_events"
  ADD COLUMN "sequence" BIGINT GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN "outcome" "AuditOutcome" NOT NULL DEFAULT 'SUCCESS',
  ADD COLUMN "requestMethod" TEXT,
  ADD COLUMN "requestPath" TEXT,
  ADD COLUMN "ipAddressHash" TEXT,
  ADD COLUMN "userAgent" TEXT,
  ADD COLUMN "reason" TEXT,
  ADD COLUMN "beforeCommitment" TEXT,
  ADD COLUMN "afterCommitment" TEXT,
  ADD COLUMN "previousHash" TEXT,
  ADD COLUMN "eventHash" TEXT;

UPDATE "audit_events"
SET "sequence" = DEFAULT,
    "eventHash" = '0x' || encode(digest(concat_ws('|', "id"::text, "action", "entityType", coalesce("entityId", ''), "createdAt"::text), 'sha256'), 'hex')
WHERE "eventHash" IS NULL;

ALTER TABLE "audit_events"
  ALTER COLUMN "sequence" SET NOT NULL,
  ALTER COLUMN "eventHash" SET NOT NULL,
  ADD CONSTRAINT "audit_events_action_check" CHECK (length(trim("action")) > 0),
  ADD CONSTRAINT "audit_events_entity_type_check" CHECK (length(trim("entityType")) > 0),
  ADD CONSTRAINT "audit_events_event_hash_check" CHECK ("eventHash" ~ '^0x[0-9a-f]{64}$'),
  ADD CONSTRAINT "audit_events_previous_hash_check" CHECK ("previousHash" IS NULL OR "previousHash" ~ '^0x[0-9a-f]{64}$'),
  ADD CONSTRAINT "audit_events_before_commitment_check" CHECK ("beforeCommitment" IS NULL OR "beforeCommitment" ~ '^0x[0-9a-f]{64}$'),
  ADD CONSTRAINT "audit_events_after_commitment_check" CHECK ("afterCommitment" IS NULL OR "afterCommitment" ~ '^0x[0-9a-f]{64}$');

CREATE UNIQUE INDEX "audit_events_sequence_key" ON "audit_events"("sequence");
CREATE UNIQUE INDEX "audit_events_eventHash_key" ON "audit_events"("eventHash");
CREATE INDEX "audit_events_action_createdAt_idx" ON "audit_events"("action", "createdAt");
CREATE INDEX "audit_events_requestId_idx" ON "audit_events"("requestId");

ALTER TABLE "audit_events" DROP CONSTRAINT "audit_events_actorId_fkey";
ALTER TABLE "audit_events" ADD CONSTRAINT "audit_events_actorId_fkey" FOREIGN KEY ("actorId") REFERENCES "users"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

CREATE OR REPLACE FUNCTION prevent_audit_event_mutation()
RETURNS TRIGGER AS $$
BEGIN
  RAISE EXCEPTION 'audit events are append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_events_append_only
BEFORE UPDATE OR DELETE ON "audit_events"
FOR EACH ROW EXECUTE FUNCTION prevent_audit_event_mutation();
